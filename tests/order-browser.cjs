const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const { randomUUID } = require('node:crypto');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
  let attempted = [], drop = true;
  await context.route('https://tworld-inventory-api.halestork64.chatgpt.site/orders**', async route => {
    const req = route.request(), data = req.postDataJSON();
    const headers = { 'access-control-allow-origin': 'http://127.0.0.1:4173', 'access-control-allow-methods': 'POST,OPTIONS', 'access-control-allow-headers': 'Content-Type', 'content-type': 'application/json' };
    if (req.method() === 'OPTIONS') return route.fulfill({ status: 204, headers });
    if (req.url().endsWith('/verify')) return route.fulfill({ status: data.code === 'Test-Partner12345' ? 200 : 401, headers, body: JSON.stringify(data.code === 'Test-Partner12345' ? { ok: true } : { error: '주문코드를 확인해주세요.' }) });
    attempted.push(data);
    if (drop) { drop = false; return route.abort('failed'); }
    return route.fulfill({ status: 201, headers, body: JSON.stringify({ receiptId: data.requestId, submittedAt: new Date().toISOString(), status: 'RECEIVED' }) });
  });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:4173/order.html?product=TH5611');
  assert.equal(await page.locator('nav a').last().innerText(), '기존 거래처 ORDER');
  assert.equal(await page.locator('#order-editor').isVisible(), false);
  await page.locator('#order-code').fill('Wrong-Partner123'); await page.locator('#order-code-form button').click(); await page.getByText('주문코드를 확인해주세요.', { exact: true }).waitFor();
  await page.locator('#order-code').fill('Test-Partner12345'); await page.locator('#order-code-form button').click(); await page.locator('#order-editor').waitFor({ state: 'visible' });
  await page.locator('#order-product').selectOption('TH5611');
  await page.getByRole('spinbutton', { name: 'S 수량', exact: true }).fill('20');
  await page.getByRole('spinbutton', { name: 'M 수량', exact: true }).fill('10');
  await page.locator('#order-add').click(); assert.equal(await page.locator('#order-total').innerText(), '30장');
  await page.getByRole('spinbutton', { name: 'S 수량', exact: true }).fill('5'); await page.locator('#order-add').click(); assert.equal(await page.locator('#order-total').innerText(), '35장'); assert.equal(await page.locator('.order-line').count(), 2);
  await page.locator('#order-agree').check();
  await fs.mkdir('outputs/order-qa', { recursive: true });
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' })); await page.waitForTimeout(400);
  await page.screenshot({ path: 'outputs/order-qa/order-desktop.png', fullPage: true, animations: 'disabled' });
  await page.locator('#order-submit').click(); await page.getByText(/같은 주문으로 다시 확인해주세요/).waitFor();
  assert.equal(await page.locator('#order-product').isDisabled(), true);
  await page.reload(); assert.equal(await page.locator('#order-code').inputValue(), '');
  await page.locator('#order-code').fill('Test-Partner12345'); await page.locator('#order-code-form button').click(); await page.locator('#order-editor').waitFor({ state: 'visible' });
  await page.locator('#order-agree').check(); await page.locator('#order-submit').click(); await page.locator('#order-success').waitFor({ state: 'visible' });
  assert.equal(attempted.length, 2); assert.equal(attempted[0].requestId, attempted[1].requestId); assert.deepEqual(attempted[0].items, attempted[1].items);
  assert.equal(await page.locator('#order-code').inputValue(), '');
  const storage = await page.evaluate(() => JSON.stringify({ ...sessionStorage, ...localStorage })); assert.ok(!storage.includes('Test-Partner12345'));
  await page.locator('#order-new').click(); await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#order-code').fill('Test-Partner12345'); await page.locator('#order-code-form button').click(); await page.locator('#order-editor').waitFor({ state: 'visible' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' })); await page.waitForTimeout(400);
  await page.screenshot({ path: 'outputs/order-qa/order-mobile.png', fullPage: true, animations: 'disabled' });
  assert.deepEqual(errors, []); await browser.close();
  console.log('PASS: order code gate, product/color/size quantities, combining lines, outage + reload retry with one request ID, no code storage, desktop/mobile layouts and JavaScript errors.');
})().catch(error => { console.error(error); process.exit(1); });
